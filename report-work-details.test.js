assert.equal(projectOverruns(project,[partial(3,275,'Approved')],0).length,0);

const {scheduleWarning}=require('./report-work-details');
const scoped={id:10,estimateItems:[{id:1,name:'Wall',plannedQuantity:100,unit:'LF',budgetHours:100}]};
const shifts=['2026-11-02','2026-11-03','2026-11-04','2026-11-05'].map(date=>({projectId:10,date}));
const metric=(hours=85,quantity=70)=>[{estimateItemId:1,actualLaborHours:hours,actualQuantity:quantity}];
const warning=(hours=85,quantity=70,days=shifts,pending=[],tasks=[])=>scheduleWarning(scoped,pending,0,days,tasks,'2026-11-01',metric(hours,quantity));
assert.match(warning().reason,/85%.*approved.*4 scheduled workdays/);
assert.equal(warning(79,89),null);
assert.match(warning(80,89).reason,/Budget nearly used/);
assert.match(warning(40,90).reason,/90% of quantity complete \(approved\)/);
assert.equal(warning(85,90,shifts.slice(0,1)),null,'one remaining workday does not trigger proximity');
assert.match(warning(101,20,[]).reason,/Labor over estimate/,'overrun does not need schedule');
const pending=[{project:0,status:'Needs review',productionEntries:[{estimateItemId:1,quantity:20,unit:'LF',laborHours:40}]}];
assert.match(warning(45,75,shifts,pending).reason,/45%.*85% including sent dailies/);
assert.match(warning(45,75,shifts,pending).reason,/95%.*75% approved/);
assert.equal(warning(45,75,shifts,[{...pending[0],status:'Draft'}]),null);
assert.equal(warning(45,75,shifts,[{...pending[0],project:1}]),null);
assert.equal(warning(45,75,shifts,[{...pending[0],deletedAt:'now'}]),null);
assert.equal(warning(45,75,shifts,[{...pending[0],status:'Approved'}]),null,'approved report not added again to metrics');
assert.equal(warning(85,70,[...shifts,...shifts,{projectId:99,date:'2026-11-06'},{projectId:10,date:'2026-11-01'},{projectId:10,date:'2026-10-30'},{projectId:10,date:'2026-11-06',status:'cancelled'}]).remaining,4,'unique future project workdays only');
assert.equal(warning(85,70,[],[],[{projectId:10,startDate:'2026-11-02',endDate:'2026-11-08',status:'in-progress'}]).remaining,5,'task span excludes weekend');
assert.equal(warning(85,70,[{projectId:10,date:'2026-11-07'}],[],[{projectId:10,startDate:'2026-11-02',endDate:'2026-11-08',status:'in-progress'}]).remaining,6,'explicit Saturday assignment counts');
assert.equal(warning(85,70,shifts,[],[{projectId:10,startDate:'2026-11-02',endDate:'2026-11-05',status:'done'}]).remaining,4,'completed tasks add no remaining days');
assert.equal(warning(40,40,[]).status,'Not enough information');
assert.equal(scheduleWarning({id:10,estimateItems:[]},[],0,shifts,[],'2026-11-01',[]).status,'Not enough information');
assert.equal(warning(50,50,[{projectId:10,date:'2026-10-30'}]),null,'completed schedule is known, not missing');
console.log('Project early warnings passed: thresholds, approved/pending separation, schedule days, exclusions and missing data.');

assert.equal(warning(85,70,[...shifts,{projectId:10,date:'2027-02-30'}]).remaining,4,'invalid calendar date excluded');
assert.equal(scheduleWarning({...scoped,estimateItems:[...scoped.estimateItems,{id:2,name:'Unknown',budgetHours:20}]},[],0,shifts,[],'2026-11-01',metric(10,10)).status,'Not enough information','partial estimate stays honest');
assert.equal(warning(20,10,shifts,[{...pending[0],productionEntries:[{estimateItemId:1,quantity:100,unit:'CY',laborHours:0}]}]),null,'incompatible quantities do not inflate progress');
